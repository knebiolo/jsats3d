def _header(title):
    return ("# %s\n\nTool version %s. Times are study wall clock (PDT stored as if UTC). "
            "1 ms of timing error is about 1 m of position error.\n\n" % (title, VERSION))


def _prepare(series, lines, rec):
    g = series[series.Rec_ID == rec].sort_values("t")
    t, y = g.t.to_numpy(float), g.tdoa_s.to_numpy(float)
    steps = sca.find_steps(t, y)
    sca.match_lines(lines[lines.Rec_ID == rec], steps)
    d, cls = sca.classify_tdiff(y, [s["k"] for s in steps])
    return t, y, steps, d, cls


# ----------------------------------------------------------------------------- signed
def cmd_signed(series, lines, out):
    j_rows, k_rows, m_rows, size_rows, level_counts = [], [], [], [], {}
    for rec in sorted(series.Rec_ID.unique()):
        t, y, steps, d, cls = _prepare(series, lines, rec)
        base = sca.baseline_level(y)
        row = {"Rec_ID": rec}
        for name in ("normal", "small_multipath_or_jitter", "large_spike_reflection_range",
                     "large_spike_beyond_reflection", "sustained_step"):
            row[name + "_s"] = float(np.nansum(d[cls == name]))
        row["total_s"] = float(np.nansum(d[1:]))
        row["last_minus_first_s"] = float(y[-1] - y[0])
        j_rows.append(row)

        st = pd.DataFrame(steps) if steps else pd.DataFrame(columns=["step_s", "has_line", "single_diff_s"])
        k_rows.append({
            "Rec_ID": rec, "steps": len(st),
            "n_up": int((st.step_s > 0).sum()), "sum_up_s": float(st.step_s[st.step_s > 0].sum()),
            "n_down": int((st.step_s < 0).sum()), "sum_down_s": float(st.step_s[st.step_s < 0].sum()),
            "sum_measured_s": float(st.step_s.sum()), "sum_single_diff_s": float(st.single_diff_s.sum()),
            "unmeasurable": int((~st.measurable).sum()) if len(st) else 0,
            "unstable_plateau": int(st.unstable_plateau.sum()) if len(st) else 0})

        missed = st[~st.has_line] if len(st) else st
        for sign, name in ((1, "up"), (-1, "down")):
            a = missed.step_s[np.sign(missed.step_s) == sign].abs().to_numpy(float)
            counts = np.histogram(a, bins=SIZE_EDGES)[0]
            for label, count in zip(SIZE_LABELS, counts):
                size_rows.append({"Rec_ID": rec, "direction": name, "size": label, "count": int(count)})

        bounds = [0] + [s["k"] for s in steps] + [len(y)]
        off_epochs, durations, minutes = 0, [], []
        for a, b in zip(bounds[:-1], bounds[1:]):
            if b <= a:
                continue
            level = float(np.median(y[a:b])) - base
            if abs(level) >= sca.MIN_STEP_S:
                off_epochs += b - a
                durations.append(b - a)
                minutes.append((t[b - 1] - t[a]) / 60.0)
                key = round(level * 2) / 2.0
                level_counts[key] = level_counts.get(key, 0) + 1
        m_rows.append({
            "Rec_ID": rec, "regimes_off_baseline": len(durations),
            "median_epochs": float(np.median(durations)) if durations else np.nan,
            "median_minutes": float(np.median(minutes)) if minutes else np.nan,
            "p90_minutes": float(np.quantile(minutes, 0.9)) if minutes else np.nan,
            "max_hours": float(np.max(minutes) / 60.0) if minutes else np.nan,
            "epochs_off_baseline_pct": 100.0 * off_epochs / max(len(y), 1)})

    sizes = pd.DataFrame(size_rows)
    size_total = (sizes.groupby(["size", "direction"], sort=False)["count"].sum().unstack("direction")
                  .reindex(SIZE_LABELS).fillna(0).astype(int).reset_index())
    one_second = (sizes[sizes["size"].isin([SIZE_LABELS[2], SIZE_LABELS[4]])].groupby("Rec_ID")["count"].sum())
    all_missed = sizes.groupby("Rec_ID")["count"].sum()
    share = pd.DataFrame({"Rec_ID": all_missed.index, "missed_steps": all_missed.to_numpy(),
                          "near_one_or_two_seconds": one_second.reindex(all_missed.index).fillna(0).astype(int).to_numpy()})
    share["pct"] = np.round(100.0 * share.near_one_or_two_seconds / share.missed_steps.clip(lower=1), 1)
    levels = (pd.DataFrame(sorted(level_counts.items(), key=lambda kv: -kv[1])[:20],
                           columns=["regime_level_minus_baseline_s", "regimes"]))

    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "followup_signed.md"), "w", encoding="utf-8") as f:
        f.write(_header("Follow-up: where the level change sits"))
        f.write("## Table J. Signed sum of tdiff by class (seconds)\n\n"
                "The classes add up to total_s exactly. If the raw level returns to where it began, total_s is near 0, "
                "and whatever the sustained_step column holds must be cancelled by the other columns.\n\n"
                + sca.md_table(pd.DataFrame(j_rows), "%.3f") + "\n")
        f.write("## Table K. Detected steps by direction (seconds)\n\n"
                + sca.md_table(pd.DataFrame(k_rows), "%.3f") + "\n")
        f.write("## Table L. Size of steps without a line, all receivers\n\n" + sca.md_table(size_total) + "\n")
        f.write("## Table L2. Share of steps without a line that are near one or two seconds\n\n"
                + sca.md_table(share, "%.1f") + "\n")
        f.write("## Table M. Regimes away from the path delay\n\n" + sca.md_table(pd.DataFrame(m_rows), "%.2f") + "\n")
        f.write("## Table M2. Most common regime levels, rounded to 0.5 s\n\n" + sca.md_table(levels, "%.1f") + "\n")
    return pd.DataFrame(j_rows), pd.DataFrame(k_rows), share


# ------------------------------------------------------------------------------ flags
def decode_flags(internal):
    parts = internal.fillna("").astype(str).str.split()
    flag = parts.str[3].fillna("").astype(str).str[0]
    return flag.map({"1": -1.0, ">": 1.0}).fillna(0.0)


def load_beacon_rows(db, tag):
    con = sqlite3.connect("file:%s?mode=ro" % os.path.abspath(db).replace("\\", "/"), uri=True)
    try:
        con.execute("PRAGMA query_only=ON")
        cols = {r[1] for r in con.execute("PRAGMA table_info(tblDetectionRaw)")}
        if "Internal" not in cols:
            raise RuntimeError("tblDetectionRaw has no Internal column in %s" % db)
        original = "seconds+COALESCE(jump_offset_s,0)" if "jump_offset_s" in cols else "seconds"
        rows = pd.read_sql("SELECT Rec_ID, %s AS o, Internal FROM tblDetectionRaw WHERE Tag_ID = ?" % original,
                           con, params=[tag])
    finally:
        con.close()
    rows["adj"] = decode_flags(rows.Internal)
    return rows.drop(columns="Internal"), ("shifted (jump_offset_s added back)" if "jump_offset_s" in cols else "unshifted")


def _join(times, rows):
    """Adjustment of the detection row at each time (NaN when no row within tolerance)."""
    rows = rows.sort_values("o").drop_duplicates("o")
    left = pd.DataFrame({"t": times, "i": np.arange(len(times))}).sort_values("t")
    m = pd.merge_asof(left, rows[["o", "adj"]], left_on="t", right_on="o",
                      direction="nearest", tolerance=JOIN_TOLERANCE_S)
    return m.sort_values("i").adj.to_numpy(float)


def cmd_flags(series, lines, rows, basis, master, out):
    master_rows = rows[rows.Rec_ID == master]
    if master_rows.empty:
        raise RuntimeError("No %s rows for the beacon tag; cannot test master flags" % master)
    n_rows, cross = [], {}
    for rec in sorted(series.Rec_ID.unique()):
        g = series[series.Rec_ID == rec].sort_values("t")
        t, y = g.t.to_numpy(float), g.tdoa_s.to_numpy(float)
        adj_l = _join(t, rows[rows.Rec_ID == rec])
        adj_m = _join(t - y, master_rows)
        joined = np.isfinite(adj_l) & np.isfinite(adj_m)
        predicted = np.where(joined, adj_l - adj_m, 0.0)
        y_fixed = y - predicted
        base = sca.baseline_level(y)
        before, after = sca.find_steps(t, y), sca.find_steps(t, y_fixed)
        sca.match_lines(lines[lines.Rec_ID == rec], before)
        observed = np.round(y - base)
        flagged = joined & (predicted != 0)
        off = joined & (observed != 0) & (np.abs(y - base) < 2.5)
        n_rows.append({
            "Rec_ID": rec, "epochs": len(y), "joined_pct": 100.0 * joined.mean(),
            "listener_flagged": int((joined & (adj_l != 0)).sum()), "master_flagged": int((joined & (adj_m != 0)).sum()),
            "plus_flags": int((joined & ((adj_l > 0) | (adj_m > 0))).sum()),
            "steps_before": len(before), "steps_after": len(after),
            "steps_without_line_before": int(sum(not s["has_line"] for s in before)),
            "within_50ms_before_pct": 100.0 * float(np.mean(np.abs(y - base) < sca.MIN_STEP_S)),
            "within_50ms_after_pct": 100.0 * float(np.mean(np.abs(y_fixed - base) < sca.MIN_STEP_S)),
            "flagged_epochs_explained_pct": (100.0 * float(np.mean(observed[flagged] == predicted[flagged]))
                                             if flagged.any() else np.nan),
            "offset_epochs_flagged_pct": (100.0 * float(np.mean(predicted[off] == observed[off]))
                                          if off.any() else np.nan)})
        for p, o in zip(predicted[joined], observed[joined]):
            key = (int(p), int(o) if abs(o) <= 2 else 99)
            cross[key] = cross.get(key, 0) + 1
    cols = [-2, -1, 0, 1, 2, 99]
    table = pd.DataFrame([{"predicted_shift_s": p, **{("observed %+d s" % c if c != 99 else "observed other"):
                                                         cross.get((p, c), 0) for c in cols}}
                          for p in (-2, -1, 0, 1, 2)])
    n = pd.DataFrame(n_rows)
    total = {"steps_before": int(n.steps_before.sum()), "steps_after": int(n.steps_after.sum()),
             "steps_removed_pct": 100.0 * (1 - n.steps_after.sum() / max(n.steps_before.sum(), 1)),
             "listener_flagged": int(n.listener_flagged.sum()), "master_flagged": int(n.master_flagged.sum()),
             "plus_flags": int(n.plus_flags.sum()), "min_joined_pct": float(n.joined_pct.min())}
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "followup_flags.md"), "w", encoding="utf-8") as f:
        f.write(_header("Follow-up: per-record one second flags on listener and master"))
        f.write("Database time basis: %s. Master receiver: %s.\n\n" % (basis, master))
        f.write("predicted shift = listener flag minus master flag. A flagged listener record should sit one second "
                "early (TDoA minus one). A flagged master record should make every listener's TDoA plus one.\n\n")
        f.write("## Totals\n\n" + sca.md_table(pd.DataFrame([total]), "%.1f") + "\n")
        f.write("## Table N. Steps before and after removing the flagged adjustment in memory\n\n"
                + sca.md_table(n, "%.2f") + "\n")
        f.write("## Table O. Predicted shift against observed whole-second offset from the path delay (epoch counts)\n\n"
                + sca.md_table(table) + "\n")
    return n, table


