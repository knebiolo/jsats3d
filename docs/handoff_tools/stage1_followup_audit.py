"""Stage 1 follow-up audit (Plan B2, 2026-11-11). Read-only. Markdown out.

DO NOT EDIT THIS FILE. Copy it, together with stage1_closure_audit.py, into the dated
output folder and run it there. It imports stage1_closure_audit from its own folder.

Three commands, each writes one markdown file into --out:

  signed        where does the level change hide?           (CSV only)
                -> followup_signed.md
  flags         do the per-record one second flags, on the listener AND on the master,
                account for the steps?                      (one database, read-only)
                -> followup_flags.md
  dispositions  what did Stage 1 itself decide about the events next to each missed
                step?                                       (CSV only)
                -> followup_dispositions.md

Nothing here changes a timestamp on disk. The flag test subtracts the documented
adjustment from an in-memory copy of the TDoA series and counts the steps again.

Flag rule (ATS SR3017 File Format 2.0 guide, same decode as
clock_jump_pre.firmware_record_adjustments): Internal group 4, first character.
'1' = minus one second on that record, '>' = plus one second, anything else = none.
"""
import argparse
import os
import sqlite3
import sys
import tempfile

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stage1_closure_audit as sca  # noqa: E402

VERSION = "followup-2026-11-11-a"
JOIN_TOLERANCE_S = 1e-4
SIZE_EDGES = [0.05, 0.25, 0.75, 1.25, 1.75, 2.25, 5.0, 25.0, np.inf]
SIZE_LABELS = ["0.05-0.25 s", "0.25-0.75 s", "0.75-1.25 s (one second)", "1.25-1.75 s",
               "1.75-2.25 s (two seconds)", "2.25-5 s", "5-25 s", ">25 s"]


def _header(title):
    return ("# %s\n\nTool version %s. Times are study wall clock (PDT stored as if UTC). "
            "1 ms of timing error is about 1 m of position error.\n\n" % (title, VERSION))


def _prepare(series, lines, rec):
    g = series[series.Rec_ID == rec].sort_values("t")
    t, y = g.t.to_numpy(float), g.tdoa_s.to_numpy(float)
    steps = sca.find_steps(t, y)
    sca.match_lines(lines[lines.Rec_ID == rec], steps)
    d, cls = sca.classify_tdiff(y, [s["k"] for s in steps])
    return t, y, steps, d, cls


# ----------------------------------------------------------------------------- signed
def cmd_signed(series, lines, out):
    j_rows, k_rows, m_rows, size_rows, level_counts = [], [], [], [], {}
    for rec in sorted(series.Rec_ID.unique()):
        t, y, steps, d, cls = _prepare(series, lines, rec)
        base = sca.baseline_level(y)
        row = {"Rec_ID": rec}
        for name in ("normal", "small_multipath_or_jitter", "large_spike_reflection_range",
                     "large_spike_beyond_reflection", "sustained_step"):
            row[name + "_s"] = float(np.nansum(d[cls == name]))
        row["total_s"] = float(np.nansum(d[1:]))
        row["last_minus_first_s"] = float(y[-1] - y[0])
        j_rows.append(row)

        st = pd.DataFrame(steps) if steps else pd.DataFrame(columns=["step_s", "has_line", "single_diff_s"])
        k_rows.append({
            "Rec_ID": rec, "steps": len(st),
            "n_up": int((st.step_s > 0).sum()), "sum_up_s": float(st.step_s[st.step_s > 0].sum()),
            "n_down": int((st.step_s < 0).sum()), "sum_down_s": float(st.step_s[st.step_s < 0].sum()),
            "sum_measured_s": float(st.step_s.sum()), "sum_single_diff_s": float(st.single_diff_s.sum()),
            "unmeasurable": int((~st.measurable).sum()) if len(st) else 0,
            "unstable_plateau": int(st.unstable_plateau.sum()) if len(st) else 0})

        missed = st[~st.has_line] if len(st) else st
        for sign, name in ((1, "up"), (-1, "down")):
            a = missed.step_s[np.sign(missed.step_s) == sign].abs().to_numpy(float)
            counts = np.histogram(a, bins=SIZE_EDGES)[0]
            for label, count in zip(SIZE_LABELS, counts):
                size_rows.append({"Rec_ID": rec, "direction": name, "size": label, "count": int(count)})

        bounds = [0] + [s["k"] for s in steps] + [len(y)]
        off_epochs, durations, minutes = 0, [], []
        for a, b in zip(bounds[:-1], bounds[1:]):
            if b <= a:
                continue
            level = float(np.median(y[a:b])) - base
            if abs(level) >= sca.MIN_STEP_S:
                off_epochs += b - a
                durations.append(b - a)
                minutes.append((t[b - 1] - t[a]) / 60.0)
                key = round(level * 2) / 2.0
                level_counts[key] = level_counts.get(key, 0) + 1
        m_rows.append({
            "Rec_ID": rec, "regimes_off_baseline": len(durations),
            "median_epochs": float(np.median(durations)) if durations else np.nan,
            "median_minutes": float(np.median(minutes)) if minutes else np.nan,
            "p90_minutes": float(np.quantile(minutes, 0.9)) if minutes else np.nan,
            "max_hours": float(np.max(minutes) / 60.0) if minutes else np.nan,
            "epochs_off_baseline_pct": 100.0 * off_epochs / max(len(y), 1)})

    sizes = pd.DataFrame(size_rows)
    size_total = (sizes.groupby(["size", "direction"], sort=False)["count"].sum().unstack("direction")
                  .reindex(SIZE_LABELS).fillna(0).astype(int).reset_index())
    one_second = (sizes[sizes["size"].isin([SIZE_LABELS[2], SIZE_LABELS[4]])].groupby("Rec_ID")["count"].sum())
    all_missed = sizes.groupby("Rec_ID")["count"].sum()
    share = pd.DataFrame({"Rec_ID": all_missed.index, "missed_steps": all_missed.to_numpy(),
                          "near_one_or_two_seconds": one_second.reindex(all_missed.index).fillna(0).astype(int).to_numpy()})
    share["pct"] = np.round(100.0 * share.near_one_or_two_seconds / share.missed_steps.clip(lower=1), 1)
    levels = (pd.DataFrame(sorted(level_counts.items(), key=lambda kv: -kv[1])[:20],
                           columns=["regime_level_minus_baseline_s", "regimes"]))

    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "followup_signed.md"), "w", encoding="utf-8") as f:
        f.write(_header("Follow-up: where the level change sits"))
        f.write("## Table J. Signed sum of tdiff by class (seconds)\n\n"
                "The classes add up to total_s exactly. If the raw level returns to where it began, total_s is near 0, "
                "and whatever the sustained_step column holds must be cancelled by the other columns.\n\n"
                + sca.md_table(pd.DataFrame(j_rows), "%.3f") + "\n")
        f.write("## Table K. Detected steps by direction (seconds)\n\n"
                + sca.md_table(pd.DataFrame(k_rows), "%.3f") + "\n")
        f.write("## Table L. Size of steps without a line, all receivers\n\n" + sca.md_table(size_total) + "\n")
        f.write("## Table L2. Share of steps without a line that are near one or two seconds\n\n"
                + sca.md_table(share, "%.1f") + "\n")
        f.write("## Table M. Regimes away from the path delay\n\n" + sca.md_table(pd.DataFrame(m_rows), "%.2f") + "\n")
        f.write("## Table M2. Most common regime levels, rounded to 0.5 s\n\n" + sca.md_table(levels, "%.1f") + "\n")
    return pd.DataFrame(j_rows), pd.DataFrame(k_rows), share


# ------------------------------------------------------------------------------ flags
def decode_flags(internal):
    parts = internal.fillna("").astype(str).str.split()
    flag = parts.str[3].fillna("").astype(str).str[0]
    return flag.map({"1": -1.0, ">": 1.0}).fillna(0.0)


def load_beacon_rows(db, tag):
    con = sqlite3.connect("file:%s?mode=ro" % os.path.abspath(db).replace("\\", "/"), uri=True)
    try:
        con.execute("PRAGMA query_only=ON")
        cols = {r[1] for r in con.execute("PRAGMA table_info(tblDetectionRaw)")}
        if "Internal" not in cols:
            raise RuntimeError("tblDetectionRaw has no Internal column in %s" % db)
        original = "seconds+COALESCE(jump_offset_s,0)" if "jump_offset_s" in cols else "seconds"
        rows = pd.read_sql("SELECT Rec_ID, %s AS o, Internal FROM tblDetectionRaw WHERE Tag_ID = ?" % original,
                           con, params=[tag])
    finally:
        con.close()
    rows["adj"] = decode_flags(rows.Internal)
    return rows.drop(columns="Internal"), ("shifted (jump_offset_s added back)" if "jump_offset_s" in cols else "unshifted")


def _join(times, rows):
    """Adjustment of the detection row at each time (NaN when no row within tolerance)."""
    rows = rows.sort_values("o").drop_duplicates("o")
    left = pd.DataFrame({"t": times, "i": np.arange(len(times))}).sort_values("t")
    m = pd.merge_asof(left, rows[["o", "adj"]], left_on="t", right_on="o",
                      direction="nearest", tolerance=JOIN_TOLERANCE_S)
    return m.sort_values("i").adj.to_numpy(float)


def cmd_flags(series, lines, rows, basis, master, out):
    master_rows = rows[rows.Rec_ID == master]
    if master_rows.empty:
        raise RuntimeError("No %s rows for the beacon tag; cannot test master flags" % master)
    n_rows, cross = [], {}
    for rec in sorted(series.Rec_ID.unique()):
        g = series[series.Rec_ID == rec].sort_values("t")
        t, y = g.t.to_numpy(float), g.tdoa_s.to_numpy(float)
        adj_l = _join(t, rows[rows.Rec_ID == rec])
        adj_m = _join(t - y, master_rows)
        joined = np.isfinite(adj_l) & np.isfinite(adj_m)
        predicted = np.where(joined, adj_l - adj_m, 0.0)
        y_fixed = y - predicted
        base = sca.baseline_level(y)
        before, after = sca.find_steps(t, y), sca.find_steps(t, y_fixed)
        sca.match_lines(lines[lines.Rec_ID == rec], before)
        observed = np.round(y - base)
        flagged = joined & (predicted != 0)
        off = joined & (observed != 0) & (np.abs(y - base) < 2.5)
        n_rows.append({
            "Rec_ID": rec, "epochs": len(y), "joined_pct": 100.0 * joined.mean(),
            "listener_flagged": int((joined & (adj_l != 0)).sum()), "master_flagged": int((joined & (adj_m != 0)).sum()),
            "plus_flags": int((joined & ((adj_l > 0) | (adj_m > 0))).sum()),
            "steps_before": len(before), "steps_after": len(after),
            "steps_without_line_before": int(sum(not s["has_line"] for s in before)),
            "within_50ms_before_pct": 100.0 * float(np.mean(np.abs(y - base) < sca.MIN_STEP_S)),
            "within_50ms_after_pct": 100.0 * float(np.mean(np.abs(y_fixed - base) < sca.MIN_STEP_S)),
            "flagged_epochs_explained_pct": (100.0 * float(np.mean(observed[flagged] == predicted[flagged]))
                                             if flagged.any() else np.nan),
            "offset_epochs_flagged_pct": (100.0 * float(np.mean(predicted[off] == observed[off]))
                                          if off.any() else np.nan)})
        for p, o in zip(predicted[joined], observed[joined]):
            key = (int(p), int(o) if abs(o) <= 2 else 99)
            cross[key] = cross.get(key, 0) + 1
    cols = [-2, -1, 0, 1, 2, 99]
    table = pd.DataFrame([{"predicted_shift_s": p, **{("observed %+d s" % c if c != 99 else "observed other"):
                                                         cross.get((p, c), 0) for c in cols}}
                          for p in (-2, -1, 0, 1, 2)])
    n = pd.DataFrame(n_rows)
    total = {"steps_before": int(n.steps_before.sum()), "steps_after": int(n.steps_after.sum()),
             "steps_removed_pct": 100.0 * (1 - n.steps_after.sum() / max(n.steps_before.sum(), 1)),
             "listener_flagged": int(n.listener_flagged.sum()), "master_flagged": int(n.master_flagged.sum()),
             "plus_flags": int(n.plus_flags.sum()), "min_joined_pct": float(n.joined_pct.min())}
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "followup_flags.md"), "w", encoding="utf-8") as f:
        f.write(_header("Follow-up: per-record one second flags on listener and master"))
        f.write("Database time basis: %s. Master receiver: %s.\n\n" % (basis, master))
        f.write("predicted shift = listener flag minus master flag. A flagged listener record should sit one second "
                "early (TDoA minus one). A flagged master record should make every listener's TDoA plus one.\n\n")
        f.write("## Totals\n\n" + sca.md_table(pd.DataFrame([total]), "%.1f") + "\n")
        f.write("## Table N. Steps before and after removing the flagged adjustment in memory\n\n"
                + sca.md_table(n, "%.2f") + "\n")
        f.write("## Table O. Predicted shift against observed whole-second offset from the path delay (epoch counts)\n\n"
                + sca.md_table(table) + "\n")
    return n, table


# ----------------------------------------------------------------------- dispositions
def cmd_dispositions(steps, jumps, evidence_only, unresolvable, out):
    has_line = steps.has_line.astype(str).str.lower().isin(["true", "1"])
    missed = steps[~has_line].copy()
    sources = []
    for name, frame in (("unresolvable", unresolvable), ("evidence_only", evidence_only), ("accepted", jumps)):
        if frame is None or frame.empty:
            continue
        f = frame.copy()
        f["source"] = name
        for col in ("note", "offset_s", "evidence"):
            if col not in f:
                f[col] = np.nan
        sources.append(f[["Rec_ID", "jump_time_s", "offset_s", "note", "evidence", "source"]])
    events = pd.concat(sources, ignore_index=True) if sources else pd.DataFrame(
        columns=["Rec_ID", "jump_time_s", "offset_s", "note", "evidence", "source"])
    rank = {"unresolvable": 0, "evidence_only": 1, "accepted": 2}
    rows = []
    for rec, g in missed.groupby("Rec_ID"):
        ev = events[events.Rec_ID == rec]
        for st in g.itertuples(index=False):
            near = ev[(ev.jump_time_s >= st.t_before_s - sca.EVENT_WINDOW_S)
                      & (ev.jump_time_s <= st.t_after_s + sca.EVENT_WINDOW_S)]
            if near.empty:
                rows.append({"Rec_ID": rec, "t_after_s": st.t_after_s, "step_s": st.step_s,
                             "disposition": "no_stage1_event", "detail": ""})
                continue
            near = near.assign(r=near.source.map(rank), dist=(near.jump_time_s - st.t_after_s).abs()).sort_values(["r", "dist"])
            best = near.iloc[0]
            if best.source == "unresolvable":
                detail = str(best.note)
            elif best.source == "evidence_only":
                size = abs(float(best.offset_s)) if pd.notna(best.offset_s) else np.nan
                detail = ("measured step below 50 ms" if size < sca.MIN_STEP_S
                          else "measured step above the 5 s maximum" if size > 5.0 else "other")
            else:
                detail = "an applied line is within 300 s but belongs to another step"
            rows.append({"Rec_ID": rec, "t_after_s": st.t_after_s, "step_s": st.step_s,
                         "disposition": str(best.source), "detail": detail})
    result = pd.DataFrame(rows)
    by_rec = (result.groupby(["Rec_ID", "disposition"]).size().unstack(fill_value=0).reset_index()
              if len(result) else pd.DataFrame())
    detail = (result.groupby(["disposition", "detail"]).size().rename("count").reset_index()
              .sort_values("count", ascending=False) if len(result) else pd.DataFrame())
    inputs = pd.DataFrame([{"missed_steps": len(missed), "stage1_accepted": len(jumps),
                            "stage1_evidence_only": len(evidence_only), "stage1_unresolvable": len(unresolvable)}])
    os.makedirs(out, exist_ok=True)
    result.to_csv(os.path.join(out, "missed_step_dispositions.csv"), index=False)
    with open(os.path.join(out, "followup_dispositions.md"), "w", encoding="utf-8") as f:
        f.write(_header("Follow-up: what Stage 1 decided next to each missed step"))
        f.write("## Inputs\n\nstage1_accepted must be 696. If it is not, the Stage 1 report run used different settings.\n\n"
                + sca.md_table(inputs) + "\n")
        f.write("## Table P. Missed steps by Stage 1 disposition, per receiver\n\n" + sca.md_table(by_rec) + "\n")
        f.write("## Table Q. Reasons\n\n" + sca.md_table(detail) + "\n")
    return result


# --------------------------------------------------------------------------- selftest
def selftest():
    rng = np.random.default_rng(11)
    n = 3000
    true_m = 1.75e9 + np.arange(n) * 61.5
    adj_l, adj_m = np.zeros(n), np.zeros(n)
    adj_l[100:121] = -1.0            # listener records flagged minus one second
    adj_m[500:531] = -1.0            # master records flagged minus one second
    rec_m = true_m + adj_m
    step = np.where(np.arange(n) >= 2000, 0.5, 0.0)       # a real, unflagged clock step
    rec_l = true_m + 0.030 + rng.normal(0, 0.0002, n) + adj_l + step
    series = pd.DataFrame({"Rec_ID": "TEST1", "t": rec_l, "transNo": np.arange(n), "tdoa_s": rec_l - rec_m})
    lines = pd.DataFrame({"Rec_ID": ["TEST1"], "jump_time_s": [rec_l[2000] - 5.0], "offset_s": [0.5],
                          "status": ["passed"], "evidence": ["OffsetChanged"]})

    def internal(a):
        return "000014 0551 00 %s041 674 A" % ("1" if a < 0 else ">" if a > 0 else "y")
    folder = tempfile.mkdtemp(prefix="followup_selftest_")
    db = os.path.join(folder, "t.db")
    con = sqlite3.connect(db)
    pd.concat([
        pd.DataFrame({"Rec_ID": "TEST1", "Tag_ID": "7DB7", "seconds": rec_l, "Internal": [internal(a) for a in adj_l]}),
        pd.DataFrame({"Rec_ID": "ZOI08", "Tag_ID": "7DB7", "seconds": rec_m, "Internal": [internal(a) for a in adj_m]}),
    ]).to_sql("tblDetectionRaw", con, index=False)
    con.commit()
    con.close()

    j, k, share = cmd_signed(series, lines, folder)
    rows, basis = load_beacon_rows(db, "7DB7")
    table_n, table_o = cmd_flags(series, lines, rows, basis, "ZOI08", folder)
    steps = pd.DataFrame(sca.find_steps(rec_l, (rec_l - rec_m)))
    sca_steps = sca.find_steps(rec_l, rec_l - rec_m)
    sca.match_lines(lines, sca_steps)
    steps = pd.DataFrame(sca_steps).assign(Rec_ID="TEST1")
    unresolvable = pd.DataFrame({"Rec_ID": ["TEST1"], "jump_time_s": [rec_l[100] + 10.0], "offset_s": [np.nan],
                                 "note": ["window clipped below 150 s by a neighbouring event"]})
    evidence_only = pd.DataFrame({"Rec_ID": ["TEST1"], "jump_time_s": [rec_l[531] - 20.0], "offset_s": [0.01]})
    disp = cmd_dispositions(steps, lines, evidence_only, unresolvable, folder)
    nrow = table_n.iloc[0]
    checks = {
        "signed classes add up": abs(j.iloc[0][[c for c in j.columns if c.endswith("_s") and c not in
                                                ("total_s", "last_minus_first_s")]].sum() - j.iloc[0].total_s) < 1e-9,
        "five steps before": int(nrow.steps_before) == 5,
        "one step after flags removed": int(nrow.steps_after) == 1,
        "all epochs joined": nrow.joined_pct == 100.0,
        "21 listener and 31 master flags": int(nrow.listener_flagged) == 21 and int(nrow.master_flagged) == 31,
        "flagged epochs explained": nrow.flagged_epochs_explained_pct == 100.0,
        "four missed steps near one second": int(share.near_one_or_two_seconds.iloc[0]) == 4,
        "four dispositions": len(disp) == 4,
        "one unresolvable and one evidence only": (int((disp.disposition == "unresolvable").sum()) == 1
                                                    and int((disp.disposition == "evidence_only").sum()) == 1),
        "two with no stage 1 event": int((disp.disposition == "no_stage1_event").sum()) == 2,
    }
    for name, ok in checks.items():
        print("%-42s %s" % (name, "OK" if ok else "FAIL"))
    print("SELFTEST PASSED" if all(checks.values()) else "SELFTEST FAILED")
    print("selftest files: %s" % folder)
    return 0 if all(checks.values()) else 1


def _read_optional(path):
    if not path or not os.path.isfile(path) or os.path.getsize(path) < 5:
        return pd.DataFrame(columns=["Rec_ID", "jump_time_s", "offset_s", "note"])
    try:
        return pd.read_csv(path, dtype={"Rec_ID": str})
    except pd.errors.EmptyDataError:
        return pd.DataFrame(columns=["Rec_ID", "jump_time_s", "offset_s", "note"])


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("command", nargs="?", choices=["signed", "flags", "dispositions"])
    p.add_argument("--series", help="series_armA_uncorrected.csv")
    p.add_argument("--lines", help="stage1_correction_lines.csv")
    p.add_argument("--db", help="flags: database holding tblDetectionRaw with Internal (opened read-only)")
    p.add_argument("--tag", default="7DB7")
    p.add_argument("--master", default="ZOI08")
    p.add_argument("--steps", help="dispositions: steps_detected.csv from the closure audit")
    p.add_argument("--stage1-report", help="dispositions: folder with jumps.csv, evidence_only.csv, unresolvable.csv")
    p.add_argument("--out")
    p.add_argument("--selftest", action="store_true")
    args = p.parse_args(argv)
    if args.selftest:
        return selftest()
    if not args.command or not args.out:
        p.error("a command and --out are required")
    if args.command in ("signed", "flags"):
        if not (args.series and args.lines):
            p.error("--series and --lines are required")
        series = pd.read_csv(args.series, dtype={"Rec_ID": str}).dropna(subset=["t", "tdoa_s"])
        lines = pd.read_csv(args.lines, dtype={"Rec_ID": str})
        for col in ("status", "evidence"):
            if col not in lines:
                lines[col] = ""
        if args.command == "signed":
            cmd_signed(series, lines, args.out)
            print("Report: %s" % os.path.join(args.out, "followup_signed.md"))
        else:
            if not args.db:
                p.error("--db is required")
            rows, basis = load_beacon_rows(args.db, args.tag)
            n, _ = cmd_flags(series, lines, rows, basis, args.master, args.out)
            print("steps before %d | after %d | min joined %.2f%%" % (n.steps_before.sum(), n.steps_after.sum(), n.joined_pct.min()))
            print("Report: %s" % os.path.join(args.out, "followup_flags.md"))
    else:
        if not (args.steps and args.stage1_report):
            p.error("--steps and --stage1-report are required")
        steps = pd.read_csv(args.steps, dtype={"Rec_ID": str})
        jumps = _read_optional(os.path.join(args.stage1_report, "jumps.csv"))
        cmd_dispositions(steps, jumps, _read_optional(os.path.join(args.stage1_report, "evidence_only.csv")),
                         _read_optional(os.path.join(args.stage1_report, "unresolvable.csv")), args.out)
        print("Report: %s" % os.path.join(args.out, "followup_dispositions.md"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
