def cmd_dispositions(steps, jumps, evidence_only, unresolvable, out):
    has_line = steps.has_line.astype(str).str.lower().isin(["true", "1"])
    missed = steps[~has_line].copy()
    sources = []
    for name, frame in (("unresolvable", unresolvable), ("evidence_only", evidence_only), ("accepted", jumps)):
        if frame is None or frame.empty:
            continue
        f = frame.copy()
        f["source"] = name
        for col in ("note", "offset_s", "evidence"):
            if col not in f:
                f[col] = np.nan
        sources.append(f[["Rec_ID", "jump_time_s", "offset_s", "note", "evidence", "source"]])
    events = pd.concat(sources, ignore_index=True) if sources else pd.DataFrame(
        columns=["Rec_ID", "jump_time_s", "offset_s", "note", "evidence", "source"])
    rank = {"unresolvable": 0, "evidence_only": 1, "accepted": 2}
    rows = []
    for rec, g in missed.groupby("Rec_ID"):
        ev = events[events.Rec_ID == rec]
        for st in g.itertuples(index=False):
            near = ev[(ev.jump_time_s >= st.t_before_s - sca.EVENT_WINDOW_S)
                      & (ev.jump_time_s <= st.t_after_s + sca.EVENT_WINDOW_S)]
            if near.empty:
                rows.append({"Rec_ID": rec, "t_after_s": st.t_after_s, "step_s": st.step_s,
                             "disposition": "no_stage1_event", "detail": ""})
                continue
            near = near.assign(r=near.source.map(rank), dist=(near.jump_time_s - st.t_after_s).abs()).sort_values(["r", "dist"])
            best = near.iloc[0]
            if best.source == "unresolvable":
                detail = str(best.note)
            elif best.source == "evidence_only":
                size = abs(float(best.offset_s)) if pd.notna(best.offset_s) else np.nan
                detail = ("measured step below 50 ms" if size < sca.MIN_STEP_S
                          else "measured step above the 5 s maximum" if size > 5.0 else "other")
            else:
                detail = "an applied line is within 300 s but belongs to another step"
            rows.append({"Rec_ID": rec, "t_after_s": st.t_after_s, "step_s": st.step_s,
                         "disposition": str(best.source), "detail": detail})
    result = pd.DataFrame(rows)
    by_rec = (result.groupby(["Rec_ID", "disposition"]).size().unstack(fill_value=0).reset_index()
              if len(result) else pd.DataFrame())
    detail = (result.groupby(["disposition", "detail"]).size().rename("count").reset_index()
              .sort_values("count", ascending=False) if len(result) else pd.DataFrame())
    inputs = pd.DataFrame([{"missed_steps": len(missed), "stage1_accepted": len(jumps),
                            "stage1_evidence_only": len(evidence_only), "stage1_unresolvable": len(unresolvable)}])
    os.makedirs(out, exist_ok=True)
    result.to_csv(os.path.join(out, "missed_step_dispositions.csv"), index=False)
    with open(os.path.join(out, "followup_dispositions.md"), "w", encoding="utf-8") as f:
        f.write(_header("Follow-up: what Stage 1 decided next to each missed step"))
        f.write("## Inputs\n\nstage1_accepted must be 696. If it is not, the Stage 1 report run used different settings.\n\n"
                + sca.md_table(inputs) + "\n")
        f.write("## Table P. Missed steps by Stage 1 disposition, per receiver\n\n" + sca.md_table(by_rec) + "\n")
        f.write("## Table Q. Reasons\n\n" + sca.md_table(detail) + "\n")
    return result



