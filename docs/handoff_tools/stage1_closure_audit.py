"""Stage 1 closure audit + tdiff classification (read-only, CSV in, markdown out).

Written 2026-11-10 for the Plan B handoff (docs/llm_handoff_PLAN_B_clock_closure_2026-11-10.md).
DO NOT EDIT THIS FILE. Copy it into the dated output folder and run it there.

Question it answers: the Stage 1 corrected beacon series drifts by seconds while the raw
series returns to its path-delay baseline. Is that drift (a) real jumps Stage 1 never
saw, (b) applied offsets with the wrong size, or (c) applied offsets where the raw series
never stepped? The script decomposes the drift into those three terms per receiver.

Inputs (both produced on 2026-11-09, never modified here):
    series_armA_uncorrected.csv   Rec_ID, t, transNo, tdoa_s   (original receiver time)
    stage1_correction_lines.csv   Rec_ID, jump_time_s, offset_s, status, evidence

Outputs (all inside --out):
    closure_report.md      every table the reviewer needs, plain markdown
    steps_detected.csv     one row per sustained level step found in the raw series
    line_matches.csv       one row per applied Stage 1 line with its match class
    tdiff_classes.csv      per receiver counts of the tdiff classes

No database access. No timestamps are changed anywhere. Nothing here is a correction.

Fixed constants (project values, not tuned):
    0.0005 s   timing budget
    0.05 s     jump application floor
    0.25 s     upper bound of a reflection delay (beacon_pairwise_dbscan.MAX_REFLECTION_DELAY_S)
    300 s      event window used by Stage 1
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

BUDGET_S = 0.0005
MIN_STEP_S = 0.05
MAX_REFLECTION_S = 0.25
EVENT_WINDOW_S = 300.0
EDGE_EPOCHS = 5          # odd on purpose: two toggled epochs out of five cannot move the median
LEVEL_EPOCHS = 5         # epochs per side to measure a step (same as the 11-07 ledger audit)
UNSTABLE_SPREAD_S = 0.5  # plateau spread above this = unstable (11-07 audit definition)
COMMON_MODE_S = 180.0    # three nominal periods


def baseline_level(y):
    """Path-delay level: median of the epochs that are physically possible delays."""
    inside = y[np.abs(y) < MAX_REFLECTION_S]
    if len(inside) < 10:
        return np.nan
    return float(np.median(inside))


def find_steps(t, y):
    """Sustained level steps in one receiver's series. Returns a list of dicts.

    An edge at index k needs both: the single difference y[k]-y[k-1] is at least the
    floor, and the median of the next EDGE_EPOCHS epochs differs from the median of the
    previous EDGE_EPOCHS by at least the floor with the same sign. A one-epoch spike
    fails the second test because the level comes back.
    """
    n = len(y)
    s = pd.Series(y)
    pre = s.shift(1).rolling(EDGE_EPOCHS).median().to_numpy()
    post = s[::-1].rolling(EDGE_EPOCHS).median()[::-1].to_numpy()
    sustained = post - pre
    d = np.diff(y, prepend=np.nan)
    with np.errstate(invalid="ignore"):
        edge = ((np.abs(d) >= MIN_STEP_S) & (np.abs(sustained) >= MIN_STEP_S)
                & (np.sign(d) == np.sign(sustained)))
    edges = np.flatnonzero(edge)
    steps = []
    for i, k in enumerate(edges):
        lo = edges[i - 1] if i > 0 else 0
        hi = edges[i + 1] if i + 1 < len(edges) else n
        before = y[max(lo, k - LEVEL_EPOCHS):k]
        after = y[k:min(hi, k + LEVEL_EPOCHS)]
        measurable = len(before) >= 3 and len(after) >= 3
        magnitude = float(np.median(after) - np.median(before)) if measurable else float(sustained[k])
        spread = float(max(np.ptp(before), np.ptp(after))) if measurable else np.nan
        steps.append({
            "k": int(k), "t_before_s": float(t[k - 1]), "t_after_s": float(t[k]),
            "bracket_s": float(t[k] - t[k - 1]), "step_s": magnitude,
            "single_diff_s": float(d[k]), "n_before": int(len(before)), "n_after": int(len(after)),
            "plateau_spread_s": spread,
            "unstable_plateau": bool(measurable and spread > UNSTABLE_SPREAD_S),
            "measurable": bool(measurable)})
    return steps


def classify_tdiff(y, step_index):
    """Drew's tdiff idea made explicit. Every epoch difference gets one class."""
    d = np.diff(y, prepend=np.nan)
    a = np.abs(d)
    cls = np.full(len(y), "normal", dtype=object)
    cls[a >= BUDGET_S] = "small_multipath_or_jitter"
    cls[a >= MIN_STEP_S] = "large_spike_reflection_range"
    cls[a >= MAX_REFLECTION_S] = "large_spike_beyond_reflection"
    cls[list(step_index)] = "sustained_step"
    cls[0] = "first_epoch"
    return d, cls


def match_lines(lines, steps):
    """One to one match of applied lines to detected steps for one receiver."""
    used = set()
    out = []
    for line in lines.sort_values("jump_time_s").itertuples(index=False):
        best, best_err = None, None
        for j, st in enumerate(steps):
            if j in used:
                continue
            if st["t_before_s"] - EVENT_WINDOW_S <= line.jump_time_s <= st["t_after_s"] + EVENT_WINDOW_S:
                err = abs(line.offset_s - st["step_s"])
                if best is None or err < best_err:
                    best, best_err = j, err
        row = {"Rec_ID": line.Rec_ID, "jump_time_s": float(line.jump_time_s),
               "offset_s": float(line.offset_s), "status": getattr(line, "status", ""),
               "evidence": getattr(line, "evidence", "")}
        if best is None:
            row.update(match="line_without_step", step_s=np.nan, error_s=np.nan, unstable_plateau=False)
        else:
            used.add(best)
            st = steps[best]
            ok = best_err <= MIN_STEP_S and np.sign(line.offset_s) == np.sign(st["step_s"])
            row.update(match="confirmed" if ok else "magnitude_mismatch", step_s=st["step_s"],
                       error_s=float(line.offset_s - st["step_s"]),
                       unstable_plateau=st["unstable_plateau"])
        out.append(row)
    for j, st in enumerate(steps):
        st["has_line"] = j in used
    return out


def audit_receiver(rec, series, lines):
    g = series.sort_values("t")
    t = g.t.to_numpy(float)
    y = g.tdoa_s.to_numpy(float)
    base = baseline_level(y)
    steps = find_steps(t, y)
    d, cls = classify_tdiff(y, [st["k"] for st in steps])
    matches = match_lines(lines, steps)
    for st in steps:
        st["Rec_ID"] = rec

    order = lines.sort_values("jump_time_s")
    times = order.jump_time_s.to_numpy(float)
    cum = np.cumsum(order.offset_s.to_numpy(float)) if len(order) else np.array([])
    idx = np.searchsorted(times, t, side="right") - 1
    applied = np.where(idx >= 0, cum[np.clip(idx, 0, max(len(cum) - 1, 0))] if len(cum) else 0.0, 0.0)
    corrected = y - applied

    head, tail = slice(0, min(50, len(y))), slice(max(0, len(y) - 50), len(y))
    raw_change = float(np.median(y[tail]) - np.median(y[head]))
    corrected_change = float(np.median(corrected[tail]) - np.median(corrected[head]))
    m = pd.DataFrame(matches) if matches else pd.DataFrame(columns=["match", "offset_s", "step_s", "error_s"])
    missed = [st for st in steps if not st["has_line"]]
    sum_missed = float(sum(st["step_s"] for st in missed))
    sum_size_error = float(-m.loc[m.match.isin(["confirmed", "magnitude_mismatch"]), "error_s"].sum()) if len(m) else 0.0
    sum_phantom = float(-m.loc[m.match == "line_without_step", "offset_s"].sum()) if len(m) else 0.0
    explained = sum_missed + sum_size_error + sum_phantom
    summary = {
        "Rec_ID": rec, "epochs": len(y), "baseline_ms": base * 1e3 if np.isfinite(base) else np.nan,
        "raw_within_50ms_pct": 100.0 * float(np.mean(np.abs(y - base) < MIN_STEP_S)),
        "stage1_within_50ms_pct": 100.0 * float(np.mean(np.abs(corrected - base) < MIN_STEP_S)),
        "lines": len(lines), "steps_found": len(steps),
        "confirmed": int((m.match == "confirmed").sum()) if len(m) else 0,
        "magnitude_mismatch": int((m.match == "magnitude_mismatch").sum()) if len(m) else 0,
        "line_without_step": int((m.match == "line_without_step").sum()) if len(m) else 0,
        "step_without_line": len(missed),
        "missed_on_unstable_plateau": int(sum(st["unstable_plateau"] for st in missed)),
        "final_cum_offset_s": float(cum[-1]) if len(cum) else 0.0,
        "raw_level_change_s": raw_change, "corrected_level_change_s": corrected_change,
        "term_missed_steps_s": sum_missed, "term_size_error_s": sum_size_error,
        "term_phantom_lines_s": sum_phantom, "unexplained_s": corrected_change - explained}

    # What-if, in memory only: remove each regime's level relative to the baseline.
    bounds = [0] + [st["k"] for st in steps] + [len(y)]
    anchored = y.copy()
    for a, b in zip(bounds[:-1], bounds[1:]):
        if b > a:
            level = float(np.median(y[a:b]))
            if abs(level - base) >= MIN_STEP_S:
                anchored[a:b] = y[a:b] - (level - base)
    summary["level_anchored_within_50ms_pct"] = 100.0 * float(np.mean(np.abs(anchored - base) < MIN_STEP_S))

    counts = pd.Series(cls).value_counts().to_dict()
    counts["Rec_ID"] = rec
    return summary, steps, matches, counts, d


def common_mode(steps):
    """Missed steps that three or more receivers share: candidates for a master clock step."""
    missed = pd.DataFrame([s for s in steps if not s["has_line"]])
    if missed.empty:
        return pd.DataFrame(columns=["t_after_s", "step_s", "receivers", "n"])
    missed = missed.sort_values("t_after_s").reset_index(drop=True)
    groups, taken = [], set()
    for i, row in missed.iterrows():
        if i in taken:
            continue
        near = missed[(missed.t_after_s - row.t_after_s).abs().le(COMMON_MODE_S)
                      & (missed.step_s - row.step_s).abs().le(MIN_STEP_S)
                      & ~missed.index.isin(taken)]
        near = near.drop_duplicates("Rec_ID")
        if len(near) >= 3:
            taken.update(near.index)
            groups.append({"t_after_s": float(near.t_after_s.median()), "step_s": float(near.step_s.median()),
                           "n": int(len(near)), "receivers": ";".join(sorted(near.Rec_ID))})
    return pd.DataFrame(groups)


def log_histogram(diffs):
    a = np.abs(np.concatenate(diffs))
    a = a[np.isfinite(a) & (a > 0)]
    edges = [0, 1e-5, 1e-4, 5e-4, 1.5e-3, 1e-2, 5e-2, 0.25, 0.75, 1.25, 5.0, 25.0, np.inf]
    labels = ["<0.01 ms", "0.01-0.1 ms", "0.1-0.5 ms", "0.5-1.5 ms", "1.5-10 ms", "10-50 ms",
              "50-250 ms", "0.25-0.75 s", "0.75-1.25 s", "1.25-5 s", "5-25 s", ">25 s"]
    counts = np.histogram(a, bins=edges)[0]
    return pd.DataFrame({"abs_tdiff": labels, "count": counts,
                         "pct": np.round(100.0 * counts / max(len(a), 1), 3)})


def cluster_count(diffs, seed=20261110, sample=200000):
    """Drew's question 'how many clusters': BIC of 1-6 Gaussian groups on log10|tdiff|."""
    try:
        from sklearn.mixture import GaussianMixture
    except Exception as error:  # report, do not guess
        return None, "sklearn not available: %s" % error
    a = np.abs(np.concatenate(diffs))
    a = a[np.isfinite(a) & (a > 0)]
    x = np.log10(a)
    rng = np.random.default_rng(seed)
    if len(x) > sample:
        x = rng.choice(x, sample, replace=False)
    rows = []
    try:
        for k in range(1, 7):
            gm = GaussianMixture(n_components=k, random_state=seed, n_init=2).fit(x.reshape(-1, 1))
            order = np.argsort(gm.means_.ravel())
            rows.append({"groups": k, "bic": round(float(gm.bic(x.reshape(-1, 1))), 1),
                         "centres_ms": " | ".join("%.3g" % (10 ** gm.means_.ravel()[i] * 1e3) for i in order),
                         "weights_pct": " | ".join("%.1f" % (100 * gm.weights_[i]) for i in order)})
    except Exception as error:  # Table G is optional; report the failure, keep the audit
        return None, "Table G not computed (%s: %s). Report this line; do not work around it." % (
            type(error).__name__, error)
    return pd.DataFrame(rows), ""


def md_table(frame, floatfmt="%.3f"):
    if frame is None or frame.empty:
        return "_none_\n"
    cols = list(frame.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in frame.itertuples(index=False):
        cells = []
        for value in row:
            if isinstance(value, (float, np.floating)):
                cells.append("" if not np.isfinite(value) else floatfmt % value)
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def run(series, lines, out):
    os.makedirs(out, exist_ok=True)
    series = series.dropna(subset=["t", "tdoa_s"])
    summaries, all_steps, all_matches, all_counts, diffs = [], [], [], [], []
    for rec in sorted(series.Rec_ID.unique()):
        s, steps, matches, counts, d = audit_receiver(
            rec, series[series.Rec_ID == rec], lines[lines.Rec_ID == rec])
        summaries.append(s)
        all_steps.extend(steps)
        all_matches.extend(matches)
        all_counts.append(counts)
        diffs.append(d[1:])
    summary = pd.DataFrame(summaries)
    steps = pd.DataFrame(all_steps)
    matches = pd.DataFrame(all_matches)
    classes = pd.DataFrame(all_counts).fillna(0).set_index("Rec_ID").astype(int).reset_index()
    shared = common_mode(all_steps)
    hist = log_histogram(diffs)
    bic, bic_note = cluster_count(diffs)

    steps.to_csv(os.path.join(out, "steps_detected.csv"), index=False)
    matches.to_csv(os.path.join(out, "line_matches.csv"), index=False)
    classes.to_csv(os.path.join(out, "tdiff_classes.csv"), index=False)

    a = summary[["Rec_ID", "epochs", "baseline_ms", "raw_within_50ms_pct", "stage1_within_50ms_pct",
                 "level_anchored_within_50ms_pct"]]
    b = summary[["Rec_ID", "lines", "steps_found", "confirmed", "magnitude_mismatch",
                 "line_without_step", "step_without_line", "missed_on_unstable_plateau"]]
    c = summary[["Rec_ID", "final_cum_offset_s", "raw_level_change_s", "corrected_level_change_s",
                 "term_missed_steps_s", "term_size_error_s", "term_phantom_lines_s", "unexplained_s"]]
    by_status = (matches.groupby(["status", "match"]).size().unstack(fill_value=0).reset_index()
                 if len(matches) else pd.DataFrame())
    worst = pd.DataFrame()
    if len(steps):
        missed = steps[~steps.has_line].copy()
        missed["abs"] = missed.step_s.abs()
        worst = missed.sort_values("abs", ascending=False).head(40)[
            ["Rec_ID", "t_before_s", "t_after_s", "bracket_s", "step_s", "plateau_spread_s", "unstable_plateau"]]
        worst.insert(1, "local_time_PDT", pd.to_datetime(worst.t_after_s, unit="s").dt.strftime("%Y-%m-%d %H:%M:%S"))
    total = {
        "lines": int(summary.lines.sum()), "steps_found": int(summary.steps_found.sum()),
        "confirmed": int(summary.confirmed.sum()), "magnitude_mismatch": int(summary.magnitude_mismatch.sum()),
        "line_without_step": int(summary.line_without_step.sum()),
        "step_without_line": int(summary.step_without_line.sum()),
        "max_abs_unexplained_s": float(summary.unexplained_s.abs().max())}

    with open(os.path.join(out, "closure_report.md"), "w", encoding="utf-8") as f:
        f.write("# Stage 1 closure audit\n\n")
        f.write("Times are study wall clock (PDT stored as if UTC). 1 ms of timing error is about 1 m of position error.\n\n")
        f.write("## Totals\n\n" + md_table(pd.DataFrame([total])) + "\n")
        f.write("## Table A. Level share within 50 ms of the path-delay baseline\n\n" + md_table(a, "%.2f") + "\n")
        f.write("## Table B. Applied lines against steps found in the raw series\n\n" + md_table(b) + "\n")
        f.write("## Table C. Drift decomposition (seconds)\n\n"
                "corrected_level_change = term_missed_steps + term_size_error + term_phantom_lines + unexplained.\n\n"
                + md_table(c, "%.4f") + "\n")
        f.write("## Table D. Match class by Stage 1 validation status\n\n" + md_table(by_status) + "\n")
        f.write("## Table E. tdiff classes per receiver (epoch counts)\n\n" + md_table(classes) + "\n")
        f.write("## Table F. |tdiff| histogram, all receivers\n\n" + md_table(hist) + "\n")
        f.write("## Table G. Number of groups in log10|tdiff| (lowest BIC is best)\n\n"
                + (md_table(bic, "%.1f") if bic is not None else bic_note + "\n") + "\n")
        f.write("## Table H. Missed steps shared by three or more receivers (master candidates)\n\n"
                + md_table(shared, "%.4f") + "\n")
        f.write("## Table I. Forty largest steps without a line\n\n" + md_table(worst, "%.4f") + "\n")
    return summary, steps, matches, classes


def selftest():
    rng = np.random.default_rng(7)
    n = 4000
    t = 1.75e9 + np.arange(n) * 61.5
    y = 0.030 + rng.normal(0, 0.0002, n)
    y[rng.choice(n, 200, replace=False)] += rng.uniform(0.002, 0.1, 200)   # reflections (spikes)
    y[1000:1800] += 1.0      # jump up at 1000 (has a line), return at 1800 (no line: missed)
    y[2500:] -= 0.6          # jump at 2500 with a line of the wrong size
    for k in (300, 301, 3300):
        y[k] += 1.0          # single epoch one second toggles
    series = pd.DataFrame({"Rec_ID": "TEST1", "t": t, "transNo": np.arange(n), "tdoa_s": y})
    quiet = pd.DataFrame({"Rec_ID": "TEST2", "t": t, "transNo": np.arange(n),
                          "tdoa_s": 0.020 + rng.normal(0, 0.0002, n)})
    lines = pd.DataFrame({
        "Rec_ID": ["TEST1", "TEST1", "TEST1"],
        "jump_time_s": [t[1000] - 20.0, t[2500] - 10.0, t[3600]],
        "offset_s": [1.0, -0.9, 0.4], "status": ["passed", "unverifiable", "unverifiable"],
        "evidence": ["OffsetChanged"] * 3})
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_selftest_closure")
    summary, steps, matches, classes = run(pd.concat([series, quiet]), lines, out)
    s = summary.set_index("Rec_ID").loc["TEST1"]
    checks = {
        "three sustained steps found": int(s.steps_found) == 3,
        "one confirmed line": int(s.confirmed) == 1,
        "one magnitude mismatch": int(s.magnitude_mismatch) == 1,
        "one line without step": int(s.line_without_step) == 1,
        "one missed step": int(s.step_without_line) == 1,
        "missed term is -1.0 s": abs(s.term_missed_steps_s + 1.0) < 0.005,
        "size error term is +0.3 s": abs(s.term_size_error_s - 0.3) < 0.005,
        "phantom term is -0.4 s": abs(s.term_phantom_lines_s + 0.4) < 1e-9,
        "drift fully explained": abs(s.unexplained_s) < 0.005,
        "quiet receiver has no steps": int(summary.set_index("Rec_ID").loc["TEST2"].steps_found) == 0,
        "level anchored recovers baseline": s.level_anchored_within_50ms_pct > 97.0,   # reflections above 50 ms remain
    }
    for name, ok in checks.items():
        print("%-40s %s" % (name, "OK" if ok else "FAIL"))
    print("SELFTEST PASSED" if all(checks.values()) else "SELFTEST FAILED")
    return 0 if all(checks.values()) else 1


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--series", help="series_armA_uncorrected.csv")
    p.add_argument("--lines", help="stage1_correction_lines.csv")
    p.add_argument("--out", help="output folder (created if missing)")
    p.add_argument("--selftest", action="store_true", help="run on synthetic data with known answers")
    args = p.parse_args(argv)
    if args.selftest:
        return selftest()
    if not (args.series and args.lines and args.out):
        p.error("--series, --lines and --out are required")
    series = pd.read_csv(args.series, dtype={"Rec_ID": str})
    lines = pd.read_csv(args.lines, dtype={"Rec_ID": str})
    need = {"Rec_ID", "jump_time_s", "offset_s"}
    if not need <= set(lines.columns) or not {"Rec_ID", "t", "tdoa_s"} <= set(series.columns):
        raise ValueError("Input columns missing; refusing to guess")
    for col in ("status", "evidence"):
        if col not in lines:
            lines[col] = ""
    summary, steps, matches, classes = run(series, lines, args.out)
    print("receivers %d | lines %d | steps found %d | confirmed %d | missed %d | max unexplained %.4f s"
          % (len(summary), summary.lines.sum(), summary.steps_found.sum(), summary.confirmed.sum(),
             summary.step_without_line.sum(), summary.unexplained_s.abs().max()))
    print("Report: %s" % os.path.join(args.out, "closure_report.md"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
