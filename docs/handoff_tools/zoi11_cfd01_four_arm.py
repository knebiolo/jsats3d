def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", nargs="?", choices=["preflight", "identity", "events", "score", "plots"])
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--scripts-dir", help="folder that holds drag_test_figures_2025.py")
    for key, name, _, _, _ in ARMS:
        parser.add_argument("--arm" + key, help="database of arm %s" % name)
    parser.add_argument("--out", help="output folder (must exist)")
    parser.add_argument("--gps-file", help="override the GPS file of drag_test_figures_2025")
    parser.add_argument("--sheets-file", help="override the testing workbook of drag_test_figures_2025")
    parser.add_argument("--sample", action="store_true", help="plots: one forebay hold, one debris barrier hold, one drag")
    args = parser.parse_args(argv)
    print("zoi11_cfd01_four_arm %s" % VERSION)
    if args.selftest:
        return 0 if selftest(args.scripts_dir) else 1
    if not args.command:
        parser.error("give a command or --selftest")
    missing = [n for n in ("scripts_dir", "armN", "armZ", "armC", "armZC", "out") if not getattr(args, n)]
    if missing:
        parser.error("missing: %s" % ", ".join("--" + m.replace("_", "-") for m in missing))
    if not Path(args.out).is_dir():
        parser.error("--out folder does not exist: %s" % args.out)
    dtf = load_dtf(args.scripts_dir, args.gps_file, args.sheets_file)
    for label, path in (("GPS file", dtf.GPS_FILE), ("testing workbook", dtf.SHEETS_FILE)):
        if not Path(path).exists():
            raise SystemExit("%s not found: %s  (use --gps-file / --sheets-file)" % (label, path))
    arms = load_arms(dtf, args)
    result = {"preflight": cmd_preflight, "identity": cmd_identity, "events": cmd_events,
              "score": cmd_score, "plots": cmd_plots}[args.command](dtf, args, arms)
    return 0 if (result is not False) else 2


