def _synthetic(folder):
    """Four small databases, a GPS file and a workbook with known answers."""
    import openpyxl
    from pyproj import Transformer
    folder = Path(folder)
    ox, oy, base = 500000.0, 5140000.0, pd.Timestamp("2025-06-10 12:00:00").timestamp()
    recs = {"ZOI01": (447, 125, -11), "ZOI02": (468, 116, -12), "ZOI03": (486, 106, -10), "ZOI05": (509, 135, -3),
            "ZOI06": (476, 122, -3), "ZOI07": (443, 110, -3), "ZOI08": (460, 117, -3), "ZOI09": (478, 128, -3),
            "ZOI10": (438, 101, -3), "ZOI11": (455, 74, -3), "CFD01": (467, 69, -3)}
    rec = pd.DataFrame([dict(Rec_ID=k, X_t=v[0], Y_t=v[1], Z_t=v[2], X=v[0], Y=v[1], easting=v[0] + ox, northing=v[1] + oy)
                        for k, v in recs.items()])
    back = Transformer.from_crs(26910, 4326, always_xy=True)
    hold, hold_db = (470.0, 100.0), (460.0, 80.0)
    # FBY-S-1 12:00 to 12:02 with GPS; DB-1 12:10 to 12:12 without GPS; FBY-S-9 on another day; drag LINE-1 12:20 to 12:22
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Forebay_StaticHolds"
    lon, lat = back.transform(hold[0] + ox, hold[1] + oy)
    ws.append(["Test ID", "Lat", "Lon", "Date", "Start Time", "End Time"])
    ws.append(["FBY-S-1", lat, lon, datetime.datetime(2025, 6, 10), datetime.time(12, 0, 0), datetime.time(12, 2, 0)])
    ws.append(["DB-1", "Not Collected", None, datetime.datetime(2025, 6, 10), datetime.time(12, 10, 0), datetime.time(12, 12, 0)])
    ws.append(["FBY-S-9", lat, lon, datetime.datetime(2025, 7, 1), datetime.time(9, 0, 0), datetime.time(9, 2, 0)])
    wb.save(folder / "sheets.xlsx")
    sec = np.arange(120)
    glon, glat = back.transform(440.0 + 0.4 * sec + ox, 95.0 + 0.2 * sec + oy)
    stamp = [(pd.Timestamp("2025-06-10 12:20:00") + pd.Timedelta(seconds=int(s))).strftime("%Y-%m-%d %H:%M") for s in sec]
    pd.DataFrame(dict(long=glon, lat=glat, timestamp=stamp, line_name="LINE-1")).to_csv(folder / "gps.csv", index=False)

    sets_n = [("ZOI08", "ZOI05", "ZOI06", "ZOI07"), ("ZOI08", "ZOI06", "ZOI09", "ZOI10"), ("ZOI08", "ZOI01", "ZOI02", "ZOI03")]

    def rows_for(rng, tag, trans, t, x, y, z, sets, noise=0.3):
        out = []
        for s in sets:
            gx, gy, gz = x + rng.normal(0, noise), y + rng.normal(0, noise), z + rng.normal(0, noise)
            for root in ("A", "B"):
                good = root == "B"
                out.append(dict(transNo=trans, solNo=0, r0=s[0], r1=s[1], r2=s[2], r3=s[3],
                                X=str(gx) if good else "9999.0", Y=str(gy) if good else "9999.0", Z=str(gz) if good else "9999.0",
                                T01="0.01" if good else "9999.0", ToA=str(t + 0.01) if good else "9999.0",
                                comment="solution found" if good else "negative quadratic discriminant - no solution",
                                in_hull="True" if good else "", solution=root, Tag_ID=tag))
        return out

    paths = {}
    for key in ("N", "Z", "C", "ZC"):
        rng = np.random.default_rng(7)        # the same draws for the shared rows in every arm
        rows, det = [], []
        for tag in ("FFD3", "FC36"):
            z = -4.5 if tag == "FFD3" else -1.5
            n = 0
            for i in range(30):               # FBY-S-1: 20 transmissions with three sets, 10 with one set only
                n += 1
                t = base + 2 + i * 3.0
                rows += rows_for(rng, tag, n, t, hold[0], hold[1], z, sets_n if i < 20 else sets_n[:1])
                det.append(dict(Rec_ID="ZOI08", Tag_ID=tag, transNo=n, seconds_fix=t))
            for i in range(10):               # DB-1: one set in arm N
                n += 1
                t = base + 602 + i * 3.0
                rows += rows_for(rng, tag, n, t, hold_db[0], hold_db[1], z, sets_n[:1])
                det.append(dict(Rec_ID="ZOI08", Tag_ID=tag, transNo=n, seconds_fix=t))
            for i in range(38):               # drag LINE-1
                n += 1
                s = 3 + i * 3.0
                rows += rows_for(rng, tag, n, base + 1200 + s, 440.0 + 0.4 * s, 95.0 + 0.2 * s, z, sets_n)
                det.append(dict(Rec_ID="ZOI08", Tag_ID=tag, transNo=n, seconds_fix=base + 1200 + s))
        for added in ADDED[key]:
            erng = np.random.default_rng(100 + len(added) + ord(added[0]))
            for tag in ("FFD3", "FC36"):
                z = -4.5 if tag == "FFD3" else -1.5
                for i in range(20, 30):       # a second receiver set for the ten single set transmissions of FBY-S-1
                    rows += rows_for(erng, tag, i + 1, base + 2 + i * 3.0, hold[0], hold[1], z, [("ZOI08", added, "ZOI06", "ZOI07")])
                    det.append(dict(Rec_ID=added, Tag_ID=tag, transNo=i + 1, seconds_fix=base + 2 + i * 3.0 + 0.02))
                if added == "ZOI11":          # ZOI11 also gives the debris barrier hold its second set
                    for i in range(10):
                        rows += rows_for(erng, tag, 31 + i, base + 602 + i * 3.0, hold_db[0], hold_db[1], z,
                                         [("ZOI08", added, "ZOI06", "ZOI10")])
                        det.append(dict(Rec_ID=added, Tag_ID=tag, transNo=31 + i, seconds_fix=base + 602 + i * 3.0 + 0.02))
        frame = pd.DataFrame(rows)
        if key == "ZC":                       # one planted defect: a transmission without added rows that differs from arm N
            mask = (frame.Tag_ID == "FFD3") & (frame.transNo == 60) & (frame.solution == "B")
            frame.loc[mask, "X"] = (frame.loc[mask, "X"].astype(float) + 5.0).astype(str)
        path = folder / ("arm_%s.db" % key)
        con = sqlite3.connect(path)
        frame.to_sql("tblPositions_Deng", con, index=False)
        frame[frame.solution == "B"].to_sql("tblPositions_DengDBSCAN", con, index=False)
        pd.DataFrame(det).to_sql("tblDetectionFilterSecondary", con, index=False)
        rec.to_sql("tblReceiver", con, index=False)
        con.commit()
        con.close()
        paths[key] = path
    return paths


