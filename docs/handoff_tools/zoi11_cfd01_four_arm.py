def plot_limits(ev, dm, track):
    xs, ys = list(dm.xyz.X_t.astype(float)), list(dm.xyz.Y_t.astype(float))
    if ev["gps"]:
        xs.append(ev["x"]), ys.append(ev["y"])
    if track is not None:
        xs += [float(track.x.min()), float(track.x.max())]
        ys += [float(track.y.min()), float(track.y.max())]
    return (min(xs) - PLOT_MARGIN_M, max(xs) + PLOT_MARGIN_M), (min(ys) - PLOT_MARGIN_M, max(ys) + PLOT_MARGIN_M)


