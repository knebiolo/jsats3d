# ----------------------------------------------------------------------------- small helpers
def ro(path):
    return sqlite3.connect("file:%s?mode=ro" % str(path).replace("\\", "/"), uri=True)


def md_table(df, floatfmt="%.2f"):
    if df is None or len(df) == 0:
        return "(no rows)\n"
    out = ["| " + " | ".join(str(c) for c in df.columns) + " |", "|" + "---|" * len(df.columns)]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, (bool, np.bool_)):
                cells.append("yes" if v else "no")
            elif isinstance(v, (float, np.floating)):
                cells.append("" if not np.isfinite(v) else floatfmt % v)
            elif isinstance(v, (int, np.integer)):
                cells.append("{:,}".format(int(v)))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def tkey(series):
    """Transmission numbers as float keys (databases may store them as text)."""
    return pd.to_numeric(series, errors="coerce")


def clock(t):
    return pd.Timestamp(float(t), unit="s").strftime("%Y-%m-%d %H:%M:%S")


def per_trans(rows):
    """Per transmission medians. Same grouping as drag_test_figures_2025.hold_product."""
    if rows is None or len(rows) == 0:
        return pd.DataFrame(columns=["transNo", "x", "y", "z", "t0", "n"])
    return rows.groupby("transNo").agg(x=("X", "median"), y=("Y", "median"), z=("Z", "median"),
                                       t0=("t0", "median"), n=("X", "size")).reset_index().sort_values("t0")


def consensus_copy(positions, radius_m=10.0, minimum_sets=2):
    """Copy of ent_analysis_2025.legacy_receiver_set_consensus. Used only when the project
    function cannot be imported (self test without --scripts-dir). The self test compares both."""
    if positions.empty:
        return pd.DataFrame()
    valid = positions[np.isfinite(positions[["X", "Y", "Z", "t0"]]).all(axis=1)].copy()
    valid = valid[valid[["X", "Y", "Z"]].abs().lt(1000).all(axis=1)]
    valid["receiver_set"] = valid[list(RCOLS)].apply(lambda row: "+".join(sorted(row.astype(str))), axis=1)
    accepted = []
    for trans_no, group in valid.groupby("transNo", sort=True):
        center = group[["X", "Y"]].median()
        nearby = group[np.hypot(group.X - center.X, group.Y - center.Y) <= radius_m]
        if nearby.receiver_set.nunique() < minimum_sets:
            continue
        med = nearby[["X", "Y", "Z", "t0"]].median()
        accepted.append({"transNo": trans_no, "x": med.X, "y": med.Y, "z": med.Z, "t0": med.t0,
                         "receiver_sets": int(nearby.receiver_set.nunique()),
                         "candidate_sets": int(group.receiver_set.nunique()), "n_combinations": int(len(nearby))})
    return pd.DataFrame(accepted).sort_values("t0").reset_index(drop=True) if accepted else pd.DataFrame()


def contains(rows, receivers):
    """Boolean per row: does the receiver set of the row contain any of `receivers`?"""
    if len(rows) == 0 or not receivers:
        return pd.Series(False, index=rows.index)
    cols = [c for c in RCOLS if c in rows.columns]
    return rows[cols].astype(str).isin(list(receivers)).any(axis=1)


def nearest_distance(x, y, points):
    """XY distance from each (x, y) to the nearest of `points` (list of (px, py))."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    if not points:
        return np.full(x.shape, np.nan)
    return np.min(np.vstack([np.hypot(x - px, y - py) for px, py in points]), axis=0)


def band_counts(distances):
    d = np.asarray(distances, float)
    d = d[np.isfinite(d)]
    return [int(((d >= lo) & (d < hi)).sum()) for lo, hi, _ in BANDS]


def compare_fixes(base, arm):
    """(new, lost, both): transmissions with a fix in the arm and not in the base, and so on."""
    b, a = set(tkey(base).dropna()), set(tkey(arm).dropna())
    return a - b, b - a, a & b


def err_stats(err):
    e = np.asarray(err, float)
    e = e[np.isfinite(e)]
    if e.size == 0:
        return np.nan, np.nan, np.nan
    return float(np.median(e)), float(np.percentile(e, 90)), float(np.sqrt(np.mean(e ** 2)))


def spread(v):
    v = np.asarray(v, float)
    v = v[np.isfinite(v)]
    return float(np.std(v)) if v.size >= 2 else np.nan


