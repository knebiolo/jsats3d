def table_names(con):
    return [r[0] for r in con.execute("select name from sqlite_master where type='table' order by name")]


def load_arm(dtf, key, db):
    name, color, mpl, sym = next((a[1], a[2], a[3], a[4]) for a in ARMS if a[0] == key)
    dm = dtf.DataManager(db)
    con = ro(db)
    det = pd.DataFrame(columns=["Rec_ID", "Tag_ID", "transNo", "seconds_fix"])
    cols = [r[1] for r in con.execute("pragma table_info(tblDetectionFilterSecondary)")]
    if {"Rec_ID", "Tag_ID", "transNo", "seconds_fix"} <= set(cols):
        det = pd.read_sql("select Rec_ID, Tag_ID, transNo, seconds_fix from tblDetectionFilterSecondary "
                          "where Rec_ID in ('ZOI11','CFD01')", con)
        det["seconds_fix"] = pd.to_numeric(det.seconds_fix, errors="coerce")
    con.close()
    return dict(key=key, name=name, color=color, mpl=mpl, sym=sym, db=Path(db), dm=dm, det=det)


def load_arms(dtf, args):
    arms = {}
    for key, _, _, _, _ in ARMS:
        path = getattr(args, "arm" + key)
        if not Path(path).is_file():
            raise SystemExit("arm %s: database not found: %s" % (key, path))
        print("loading arm %s  %s" % (key, path), flush=True)
        arms[key] = load_arm(dtf, key, path)
    return arms


def data_window(dm):
    lo, hi = np.inf, -np.inf
    for f in dm.first.values():
        if len(f):
            lo, hi = min(lo, float(f.min())), max(hi, float(f.max()))
    return lo, hi


def read_holds(dtf, dm):
    """Every row of the Forebay_StaticHolds sheet that has a Test ID. Same parsing as
    DataManager.static_holds, but rows without Lat/Lon are kept (x = y = nan) when they have times."""
    import openpyxl
    from pyproj import Transformer
    wb = openpyxl.load_workbook(str(dtf.SHEETS_FILE), read_only=True)
    sheets = list(wb.sheetnames)
    rows = list(wb["Forebay_StaticHolds"].iter_rows(values_only=True))
    wb.close()
    holds = []
    if not rows:
        return holds, sheets
    header = [str(c).strip() if c is not None else "" for c in rows[0]]
    tr = Transformer.from_crs(4326, 26910, always_xy=True)
    for row in rows[1:]:
        d = dict(zip(header, row))
        tid = str(d.get("Test ID") or "").strip()
        if not tid:
            continue
        kind = "debris barrier hold" if tid.upper().startswith("DB") else ("forebay hold" if "-S-" in tid else "other hold")
        lat, lon, date, st, et = d.get("Lat"), d.get("Lon"), d.get("Date"), d.get("Start Time"), d.get("End Time")
        ev = dict(event=tid, kind=kind, x=np.nan, y=np.nan, t0=np.nan, t1=np.nan, date="", start="", end="", note="")
        try:
            if date is None or st is None or et is None:
                raise ValueError("no date or times in sheet")
            ev["t0"] = (pd.Timestamp(date) + pd.Timedelta(str(st))).tz_localize("UTC").timestamp()
            ev["t1"] = (pd.Timestamp(date) + pd.Timedelta(str(et))).tz_localize("UTC").timestamp()
            ev["date"], ev["start"], ev["end"] = str(pd.Timestamp(date).date()), str(st)[:8], str(et)[:8]
        except Exception as error:  # noqa: BLE001  (the row is listed with its reason, never dropped)
            ev["t0"] = ev["t1"] = np.nan
            ev["note"] = "times unusable: %s" % error
        if isinstance(lat, (int, float)) and isinstance(lon, (int, float)) and not pd.isna(lat) and not pd.isna(lon):
            hx, hy = tr.transform(float(lon), float(lat))
            ev["x"], ev["y"] = hx - dm.ox, hy - dm.oy
        holds.append(ev)
    return holds, sheets


def build_events(dtf, arms):
    dm = arms["N"]["dm"]
    lo, hi = data_window(dm)
    holds, sheets = read_holds(dtf, dm)
    events = list(holds)
    for line in sorted(dm.tracks):
        tr = dm.tracks[line]
        events.append(dict(event=str(line), kind="drag", x=float(tr.x.median()), y=float(tr.y.median()),
                           t0=float(tr.gtime.min()), t1=float(tr.gtime.max()), date=clock(tr.gtime.min())[:10],
                           start=clock(tr.gtime.min())[11:], end=clock(tr.gtime.max())[11:], note=""))
    for ev in events:
        ev["gps"] = bool(np.isfinite(ev["x"]) and np.isfinite(ev["y"]))
        ev["has_times"] = bool(np.isfinite(ev["t0"]) and np.isfinite(ev["t1"]))
        ev["in_window"] = bool(ev["has_times"] and ev["t1"] >= lo and ev["t0"] <= hi)
        ev["scored"] = bool(ev["in_window"])
    return events, sheets, (lo, hi)


def test_points(dm):
    return [(float(dm.xyz.at[r, "X_t"]), float(dm.xyz.at[r, "Y_t"])) for r in TEST_RECEIVERS if r in dm.xyz.index]


# ----------------------------------------------------------------------------- scoring
def score_event(dtf, arm, ev, tag, consensus_fn):
    """Numbers and fixes of one arm for one event and tag."""
    dm = arm["dm"]
    p3b = dm.p3b
    out = dict(solution_rows=0, trans_with_solution=0, fixes=0, std_x=np.nan, std_y=np.nan, std_z=np.nan,
               median_z=np.nan, median_err=np.nan, p90_err=np.nan, rmse=np.nan, candidates=np.nan,
               share_rows_added=np.nan, det_ZOI11=0, det_CFD01=0)
    empty = pd.DataFrame(columns=["transNo", "t0", "x", "y", "z", "err"])
    if p3b is None or len(p3b) == 0:
        return out, empty
    if ev["kind"] == "drag":
        prod = dtf.line_product(dm, ev["event"], tag)
        rows = prod["rows"]
        out["candidates"] = len(prod["ids"])
        fix = prod["kalman"]
        if fix is None or len(fix) == 0:
            fix = empty.copy()
        else:
            fix = fix[["transNo", "t0", "x", "y", "z"]].copy()
            fix["err"] = np.nan
            if prod["scored"] is not None and len(prod["scored"]):
                fix = fix.drop(columns="err").merge(prod["scored"][["transNo", "err"]], on="transNo", how="left")
    else:
        rows = p3b[(p3b.Tag_ID == tag) & (p3b.t0 >= ev["t0"] - 1) & (p3b.t0 <= ev["t1"] + 1)]
        fix = consensus_fn(rows) if len(rows) else pd.DataFrame()
        if fix is None or len(fix) == 0:
            fix = empty.copy()
        else:
            fix = fix[["transNo", "t0", "x", "y", "z"]].copy()
            fix["err"] = np.hypot(fix.x - ev["x"], fix.y - ev["y"]) if ev["gps"] else np.nan
    out["solution_rows"] = int(len(rows))
    out["trans_with_solution"] = int(rows.transNo.nunique()) if len(rows) else 0
    out["fixes"] = int(len(fix))
    if len(rows) and ADDED[arm["key"]]:
        out["share_rows_added"] = float(100.0 * contains(rows, ADDED[arm["key"]]).mean())
    if len(fix):
        out["std_x"], out["std_y"], out["std_z"] = spread(fix.x), spread(fix.y), spread(fix.z)
        out["median_z"] = float(np.median(fix.z))
        out["median_err"], out["p90_err"], out["rmse"] = err_stats(fix.err)
    det = arm["det"]
    if len(det):
        win = det[(det.Tag_ID == tag) & (det.seconds_fix >= ev["t0"] - 3) & (det.seconds_fix <= ev["t1"] + 3)]
        out["det_ZOI11"], out["det_CFD01"] = int((win.Rec_ID == "ZOI11").sum()), int((win.Rec_ID == "CFD01").sum())
    return out, fix.reset_index(drop=True)


def score_all(dtf, arms, events, tags, consensus_fn, only=None):
    scores, fixes = [], {}
    for ev in events:
        if not ev["scored"] or (only is not None and ev["event"] not in only):
            continue
        for tag in tags:
            for key, name, _, _, _ in ARMS:
                numbers, fix = score_event(dtf, arms[key], ev, tag, consensus_fn)
                fixes[(ev["event"], tag, key)] = fix
                scores.append(dict(event=ev["event"], kind=ev["kind"], tag=tag, arm=key, arm_name=name, gps=ev["gps"], **numbers))
        print("scored %s" % ev["event"], flush=True)
    return pd.DataFrame(scores), fixes


def pm_tables(scores, fixes, events, arms):
    """Tables V4a to V4d and the filled summary sentences."""
    points = test_points(arms["N"]["dm"])
    evmap = {e["event"]: e for e in events}
    v4b, v4c, v4d = [], [], []
    for (event, tag), block in scores.groupby(["event", "tag"], sort=False):
        ev = evmap[event]
        base = fixes[(event, tag, "N")]
        base_err = float(block[block.arm == "N"].median_err.iloc[0])
        truth_dist = float(nearest_distance([ev["x"]], [ev["y"]], points)[0]) if ev["gps"] else np.nan
        for key, name, _, _, _ in ARMS[1:]:
            fix = fixes[(event, tag, key)]
            new, lost, both = compare_fixes(base.transNo, fix.transNo)
            v4b.append(dict(event=event, tag=tag, arm=name, fixes_arm1=len(base), fixes_arm=len(fix),
                            gained=len(new), lost=len(lost), in_both=len(both)))
            gained = fix[tkey(fix.transNo).isin(new)]
            counts = band_counts(nearest_distance(gained.x, gained.y, points))
            v4c.append(dict(event=event, tag=tag, arm=name, gained=len(gained),
                            **{BANDS[i][2]: counts[i] for i in range(3)}))
            if ev["gps"]:
                arm_err = float(block[block.arm == key].median_err.iloc[0])
                a = base.assign(k=tkey(base.transNo))[["k", "err"]].dropna()
                b = fix.assign(k=tkey(fix.transNo))[["k", "err"]].dropna()
                pair = a.merge(b, on="k", suffixes=("_1", "_arm"))
                v4d.append(dict(event=event, tag=tag, arm=name, truth_to_nearer_receiver_m=truth_dist,
                                median_err_arm1=base_err, median_err_arm=arm_err, change_m=arm_err - base_err,
                                paired_fixes=len(pair),
                                paired_median_change_m=float((pair.err_arm - pair.err_1).median()) if len(pair) else np.nan))
    v4b, v4c, v4d = pd.DataFrame(v4b), pd.DataFrame(v4c), pd.DataFrame(v4d)
    if len(v4d):
        v4d = v4d.sort_values(["truth_to_nearer_receiver_m", "event", "tag", "arm"]).reset_index(drop=True)
    sentences = []
    for key, name, _, _, _ in ARMS[1:]:
        b, c = v4b[v4b.arm == name], v4c[v4c.arm == name]
        d = v4d[(v4d.arm == name) & np.isfinite(v4d.change_m)] if len(v4d) else v4d
        text = ("**%s.** %d of %d event and tag pairs gained fixes (%s transmissions gained, %s lost). Of the gained "
                "fixes, %s are %s from the nearer of ZOI11 and CFD01, %s at %s, %s %s."
                % (name, int((b.gained > 0).sum()), len(b), "{:,}".format(int(b.gained.sum())),
                   "{:,}".format(int(b.lost.sum())), "{:,}".format(int(c[BANDS[0][2]].sum())), BANDS[0][2],
                   "{:,}".format(int(c[BANDS[1][2]].sum())), BANDS[1][2],
                   "{:,}".format(int(c[BANDS[2][2]].sum())), BANDS[2][2]))
        if len(d):
            up, down = d[d.change_m > ERR_STEP_M], d[d.change_m < -ERR_STEP_M]
            text += (" On %d pairs with GPS truth and fixes in both arms, the median error rose by more than %.1f m on %d, "
                     "fell by more than %.1f m on %d, and stayed within %.1f m on %d."
                     % (len(d), ERR_STEP_M, len(up), ERR_STEP_M, len(down), ERR_STEP_M, len(d) - len(up) - len(down)))
            if len(up):
                text += (" The pairs where it rose lie %.0f to %.0f m from the nearer receiver."
                         % (up.truth_to_nearer_receiver_m.min(), up.truth_to_nearer_receiver_m.max()))
        else:
            text += " No pair has GPS truth and fixes in both arms."
        sentences.append(text)
    return v4b, v4c, v4d, sentences


